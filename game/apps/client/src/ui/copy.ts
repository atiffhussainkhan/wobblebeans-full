/** String catalogue. Child lines aim for 8 words or fewer. No baked 3D text. */

export type Audience = 'child' | 'adult'
export type CopyRole = 'button' | 'body' | 'heading' | 'label'

export interface CopyEntry {
  audience: Audience
  role: CopyRole
  screen: string
  context: string
  /** Room for about 40% expansion. Translators must fit inside this. */
  max: number
  'en-GB': string
  'en-US': string
}

function line(
  audience: Audience,
  role: CopyRole,
  screen: string,
  context: string,
  enGB: string,
  enUS?: string,
): CopyEntry {
  const us = enUS ?? enGB
  const longest = Math.max(enGB.length, us.length)
  return {
    audience,
    role,
    screen,
    context,
    max: Math.ceil(longest * 1.4),
    'en-GB': enGB,
    'en-US': us,
  }
}

const child = (
  role: CopyRole,
  screen: string,
  context: string,
  enGB: string,
  enUS?: string,
) => line('child', role, screen, context, enGB, enUS)

const adult = (
  role: CopyRole,
  screen: string,
  context: string,
  enGB: string,
  enUS?: string,
) => line('adult', role, screen, context, enGB, enUS)

